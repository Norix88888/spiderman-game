  /* 링 근처 프리미티브만 추리기 (레이마칭 비용 절감) */
  function cull(list, cx, cy, cz, reach) {
    const out = [];
    for (let i = 0; i < list.length; i++) {
      const P = list[i];
      const dx = P.cx - cx, dy = P.cy - cy, dz = P.cz - cz;
      if (Math.sqrt(dx * dx + dy * dy + dz * dz) < P.br + reach) out.push(P);
    }
    return out;
  }

  /* 링 중심에서 방향 D 로 등가면(SDF=0) 까지 이분탐색 */
  function march(list, cx, cy, cz, dx, dz, rMin, rMax) {
    let lo = 0, hi = rMax;
    if (field(cx + dx * hi, cy, cz + dz * hi, list) < 0) return rMax;
    if (field(cx, cy, cz, list) > 0) {                 // 중심이 바깥 → 안전 폴백
      let found = -1;
      for (let i = 1; i <= 8; i++) {                   // 바깥→안쪽 스캔
        const t = rMax * (i / 8);
        if (field(cx + dx * t, cy, cz + dz * t, list) < 0) { found = t; break; }
      }
      if (found < 0) return rMin;
      lo = found; hi = rMax;
    }
    for (let i = 0; i < 16; i++) {
      const m = (lo + hi) * 0.5;
      if (field(cx + dx * m, cy, cz + dz * m, list) < 0) lo = m; else hi = m;
    }
    const r = (lo + hi) * 0.5;
    return r < rMin ? rMin : (r > rMax ? rMax : r);
  }
